"""O ``alembic check`` (modelos × banco das migrações) não acha diferença — SQLite e PostgreSQL.

BANCO-3. As migrações são a verdade do banco de produção; os modelos são o que o
``alembic revision --autogenerate`` compara com elas. Divergiam em três pontos:

1. o ``env.py`` liga ``compare_server_default=True`` e, no PostgreSQL, o Alembic compara o
   default ``'{}'`` das colunas JSON rodando ``SELECT '{}'::json = '{}'`` — o tipo json não
   tem operador ``=``: ``alembic check`` e o autogenerate quebravam com ProgrammingError;
2. 12 colunas têm ``server_default`` nas migrações e não nos modelos (alunos.da_lista_piloto,
   identidades_externas.status, modulos_rede.ativo/updated_at, as 4 de notas,
   notificacoes.severidade, redes.created_at/status, usuarios.notificacoes_lidas_ate_id), e
   ``identidades_externas.created_at`` é nulável no banco (0013) e NOT NULL no modelo;
3. no SQLite, o Alembic não reconhece o default ``''`` (string vazia) como igual ao do
   modelo — as 4 colunas de indicadores_referencia saíam como diferença.

Resultado: o autogenerate propunha 17 operações espúrias (tirar defaults de produção, pôr
NOT NULL numa coluna que pode ter nulo). O teste de paridade (test_alembic) compara só nome e
tipo das colunas, FKs e nomes de índice; este roda o ``command.check`` do Alembic pelo
``env.py`` do repositório, depois de aplicar as migrações, e exige ZERO diferenças.
"""
from __future__ import annotations

import pytest
from alembic import command
from sqlalchemy import create_engine

import app.models  # noqa: F401 — registra as tabelas em Base.metadata
import app.quest.models  # noqa: F401
from app.core.migracoes import _config_da_aplicacao, aplicar_migracoes
from tests._infra_comum import pg_url  # noqa: F401 — fixture


def _alembic_check(engine) -> None:
    """``alembic check`` sobre o banco do ``engine``, pelo env.py do repositório (a conexão
    injetada é a mesma que ``aplicar_migracoes`` usa). Levanta ``AutogenerateDiffsDetected``
    com a lista de diferenças, ou o erro do banco se a comparação quebrar."""
    cfg = _config_da_aplicacao()
    with engine.connect() as conexao:
        cfg.attributes["connection"] = conexao
        command.check(cfg)


def test_alembic_check_sem_diferencas_no_sqlite(tmp_path):
    engine = create_engine(f"sqlite:///{(tmp_path / 'check.db').as_posix()}")
    try:
        aplicar_migracoes(engine)
        _alembic_check(engine)
    finally:
        engine.dispose()


@pytest.mark.postgres
def test_alembic_check_sem_diferencas_no_postgresql(pg_url):  # noqa: F811 — fixture
    engine = create_engine(pg_url)
    try:
        aplicar_migracoes(engine)
        _alembic_check(engine)
    finally:
        engine.dispose()
